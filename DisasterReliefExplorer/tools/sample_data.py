DDL = [
"""CREATE TABLE DISASTER (
  DISASTER_ID INTEGER NOT NULL PRIMARY KEY,
  DISASTER_NAME VARCHAR(100) NOT NULL,
  DISASTER_TYPE VARCHAR(30) NOT NULL,
  LOCATION VARCHAR(100) NOT NULL,
  START_DATE DATE NOT NULL,
  SEVERITY VARCHAR(15) NOT NULL CHECK (SEVERITY IN ('LOW','MEDIUM','HIGH','CRITICAL')))""",
"""CREATE TABLE ORGANIZATION (
  ORGANIZATION_ID INTEGER NOT NULL PRIMARY KEY,
  ORGANIZATION_NAME VARCHAR(100) NOT NULL,
  ORGANIZATION_TYPE VARCHAR(30) NOT NULL,
  CONTACT_NUMBER VARCHAR(20),
  LOCATION VARCHAR(100))""",
"""CREATE TABLE WAREHOUSE (
  WAREHOUSE_ID INTEGER NOT NULL PRIMARY KEY,
  WAREHOUSE_NAME VARCHAR(100) NOT NULL,
  LOCATION VARCHAR(100) NOT NULL,
  CAPACITY INTEGER NOT NULL CHECK (CAPACITY > 0))""",
"""CREATE TABLE RESOURCE (
  RESOURCE_ID INTEGER NOT NULL PRIMARY KEY,
  RESOURCE_NAME VARCHAR(100) NOT NULL,
  CATEGORY VARCHAR(40) NOT NULL,
  UNIT VARCHAR(20) NOT NULL)""",
"""CREATE TABLE INVENTORY (
  WAREHOUSE_ID INTEGER NOT NULL REFERENCES WAREHOUSE(WAREHOUSE_ID),
  RESOURCE_ID INTEGER NOT NULL REFERENCES RESOURCE(RESOURCE_ID),
  QUANTITY INTEGER NOT NULL CHECK (QUANTITY >= 0),
  PRIMARY KEY (WAREHOUSE_ID, RESOURCE_ID))""",
"""CREATE TABLE RELIEF_REQUEST (
  REQUEST_ID INTEGER NOT NULL PRIMARY KEY,
  DISASTER_ID INTEGER NOT NULL REFERENCES DISASTER(DISASTER_ID),
  REQUESTED_BY VARCHAR(100) NOT NULL,
  LOCATION VARCHAR(100) NOT NULL,
  RESOURCE_ID INTEGER NOT NULL REFERENCES RESOURCE(RESOURCE_ID),
  QUANTITY_NEEDED INTEGER NOT NULL CHECK (QUANTITY_NEEDED > 0),
  PRIORITY VARCHAR(15) NOT NULL CHECK (PRIORITY IN ('LOW','MEDIUM','HIGH','CRITICAL')),
  REQUEST_STATUS VARCHAR(20) DEFAULT 'OPEN' NOT NULL
     CHECK (REQUEST_STATUS IN ('OPEN','APPROVED','FULFILLED','CANCELLED')),
  REQUEST_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)""",
"""CREATE TABLE DELIVERY (
  DELIVERY_ID INTEGER NOT NULL PRIMARY KEY,
  REQUEST_ID INTEGER NOT NULL REFERENCES RELIEF_REQUEST(REQUEST_ID),
  WAREHOUSE_ID INTEGER NOT NULL REFERENCES WAREHOUSE(WAREHOUSE_ID),
  ORGANIZATION_ID INTEGER NOT NULL REFERENCES ORGANIZATION(ORGANIZATION_ID),
  DELIVERY_DATE DATE,
  DELIVERY_STATUS VARCHAR(20) DEFAULT 'PREPARING' NOT NULL
     CHECK (DELIVERY_STATUS IN ('PREPARING','DISPATCHED','DELIVERED','CANCELLED')))""",
"""CREATE TABLE DELIVERY_ITEM (
  DELIVERY_ID INTEGER NOT NULL REFERENCES DELIVERY(DELIVERY_ID),
  RESOURCE_ID INTEGER NOT NULL REFERENCES RESOURCE(RESOURCE_ID),
  QUANTITY INTEGER NOT NULL CHECK (QUANTITY > 0),
  PRIMARY KEY (DELIVERY_ID, RESOURCE_ID))""",
"CREATE INDEX IDX_REQUEST_PRIORITY ON RELIEF_REQUEST (PRIORITY, REQUEST_STATUS)",
"CREATE INDEX IDX_REQUEST_DISASTER ON RELIEF_REQUEST (DISASTER_ID)",
"CREATE INDEX IDX_DELIVERY_STATUS ON DELIVERY (DELIVERY_STATUS)",
"""CREATE VIEW V_PENDING_REQUESTS AS
  SELECT RR.REQUEST_ID, D.DISASTER_NAME, RR.REQUESTED_BY, R.RESOURCE_NAME,
         RR.QUANTITY_NEEDED, RR.PRIORITY, RR.REQUEST_STATUS
  FROM RELIEF_REQUEST RR
  JOIN DISASTER D ON D.DISASTER_ID = RR.DISASTER_ID
  JOIN RESOURCE R ON R.RESOURCE_ID = RR.RESOURCE_ID
  WHERE RR.REQUEST_STATUS IN ('OPEN','APPROVED')""",
"""CREATE VIEW V_INVENTORY_SUMMARY AS
  SELECT W.WAREHOUSE_NAME, R.RESOURCE_NAME, R.CATEGORY, I.QUANTITY, R.UNIT
  FROM INVENTORY I
  JOIN WAREHOUSE W ON W.WAREHOUSE_ID = I.WAREHOUSE_ID
  JOIN RESOURCE R ON R.RESOURCE_ID = I.RESOURCE_ID""",
"""CREATE VIEW V_DELIVERY_SUMMARY AS
  SELECT DL.DELIVERY_ID, RR.REQUESTED_BY, O.ORGANIZATION_NAME, W.WAREHOUSE_NAME,
         R.RESOURCE_NAME, DI.QUANTITY, DL.DELIVERY_STATUS
  FROM DELIVERY DL
  JOIN RELIEF_REQUEST RR ON RR.REQUEST_ID = DL.REQUEST_ID
  JOIN ORGANIZATION O ON O.ORGANIZATION_ID = DL.ORGANIZATION_ID
  JOIN WAREHOUSE W ON W.WAREHOUSE_ID = DL.WAREHOUSE_ID
  JOIN DELIVERY_ITEM DI ON DI.DELIVERY_ID = DL.DELIVERY_ID
  JOIN RESOURCE R ON R.RESOURCE_ID = DI.RESOURCE_ID""",
"""CREATE PROCEDURE UPDATE_REQUEST_STATUS (P_REQUEST_ID INTEGER, P_NEW_STATUS VARCHAR(20))
AS
BEGIN
  UPDATE RELIEF_REQUEST SET REQUEST_STATUS = :P_NEW_STATUS WHERE REQUEST_ID = :P_REQUEST_ID;
END""",
"""CREATE EXCEPTION EX_BAD_QTY 'Delivery quantity must be greater than zero'""",
"""CREATE EXCEPTION EX_NO_STOCK 'Stock missing or insufficient in the delivery warehouse'""",
"""CREATE TRIGGER BI_DELIVERY_ITEM_STOCK FOR DELIVERY_ITEM
ACTIVE BEFORE INSERT POSITION 0
AS
  DECLARE VARIABLE V_WH INTEGER;
  DECLARE VARIABLE V_QTY INTEGER;
BEGIN
  IF (NEW.QUANTITY <= 0) THEN EXCEPTION EX_BAD_QTY;
  SELECT WAREHOUSE_ID FROM DELIVERY WHERE DELIVERY_ID = NEW.DELIVERY_ID INTO :V_WH;
  SELECT QUANTITY FROM INVENTORY
    WHERE WAREHOUSE_ID = :V_WH AND RESOURCE_ID = NEW.RESOURCE_ID INTO :V_QTY;
  IF (V_QTY IS NULL OR V_QTY < NEW.QUANTITY) THEN EXCEPTION EX_NO_STOCK;
  UPDATE INVENTORY SET QUANTITY = QUANTITY - NEW.QUANTITY
    WHERE WAREHOUSE_ID = :V_WH AND RESOURCE_ID = NEW.RESOURCE_ID;
END""",
]

